let currentLang = "id";

function setLang(l) {
  if (!I18N[l]) l = "id";
  currentLang = l;
  localStorage.setItem("pos_lang", l);
  document.documentElement.lang = l;
  document.documentElement.dir = (l === "ar") ? "rtl" : "ltr";
}

function t(key, params) {
  let s;
  const parts = String(key).split(".");
  let obj = I18N[currentLang];
  for (const p of parts) { obj = obj && obj[p]; }
  s = obj;
  if (s === undefined || s === null) {
    obj = I18N.ar;
    for (const p of parts) { obj = obj && obj[p]; }
    s = obj;
  }
  if (s === undefined || s === null) s = key;
  if (params) {
    for (const k in params) s = String(s).split("{" + k + "}").join(params[k]);
  }
  return s;
}

function applyLang() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    try {
      const v = t(el.getAttribute("data-i18n"));
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.setAttribute("placeholder", v);
        return;
      }
      if (el.dataset.i18nHtml === "1") {
        el.innerHTML = v;
        return;
      }
      if (el.querySelector("*")) {
        return;
      }
      const cur = el.textContent;
      const m = cur.match(/^(\s*(?:[^\p{L}\p{N}\s]|\p{Extended_Pictographic})+\s*)/u);
      const mv = v.match(/^(\s*(?:[^\p{L}\p{N}\s]|\p{Extended_Pictographic})+\s*)/u);
      el.innerHTML = (m && !mv ? m[1] : "") + v;
    } catch (e) {
      if (typeof console !== "undefined") console.warn("i18n:", el, e);
    }
  });
  try { applySettings(); } catch (e) {}
}
